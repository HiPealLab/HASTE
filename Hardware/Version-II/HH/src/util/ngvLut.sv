module lut (
    input clk,
    input rst,
    input [1:0] s_a,
    input [1:0] s_ab,
    input [8:0] volt,
    output [15:0] alpha,
    output [15:0] alpha_beta
);

  wire signed [15:0] betan;
  wire signed [15:0] alphan;
  wire signed [15:0] betam;
  wire signed [15:0] alpham;
  wire signed [15:0] betah;
  wire signed [15:0] alphah;

  wire signed [15:0] alpha_beta_n;
  wire signed [15:0] alpha_beta_m;
  wire signed [15:0] alpha_beta_h;

  assign alpha_beta_n = alphan + betan;
  assign alpha_beta_m = alpham + betam;
  assign alpha_beta_h = alphah + betah;


  ivmux #(
      .WIDTH(16)
  ) a (
      .sel  (s_a),
      .i_i  (alphan),
      .i_ii (alpham),
      .i_iii(alphah),
      .i_iv (16'dz),
      .o_m  (alpha)
  );

  ivmux #(
      .WIDTH(16)
  ) ab (
      .sel  (s_ab),
      .i_i  (alpha_beta_n),
      .i_ii (alpha_beta_m),
      .i_iii(alpha_beta_h),
      .i_iv (16'dz),
      .o_m  (alpha_beta)
  );


  a_n_mem a_n (
      .clk(clk),
      .rst(rst),
      .addr(volt),
