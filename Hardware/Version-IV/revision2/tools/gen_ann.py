#!/usr/bin/env python3
"""Build + bit-exact model of the quantized 8-bit ANN baseline core
(revision2/rtl/ann_q8.sv).

  gen_ann.py build TOPO          -> revision2/build_ann/ann_TOPO/{syn.mem, ann_params.svh, quant.json}
  gen_ann.py data                -> revision2/build_ann/{inputs.mem, labels.mem} (1000 test images, uint8)
  gen_ann.py model TOPO          -> revision2/build_ann/ann_TOPO/ref_int.txt (+ accuracy report)

Quantisation (integer-only, Jacob et al. 2018):
  inputs  a0 = round(x * 255), x = 8x8 bilinear pixel in [0,1]  (scale s_0 = 1/255)
  weights the int8 synMem of the SNN builds: q = round(W/m*127), scale s_w = m/127
          (tools/gen_mem.quantise, identical bits)
  hidden  scale s_l = max ReLU activation on 2000 MNIST *training* images / 255
          a_l = clamp(round(acc * s_{l-1} s_w / s_l), 0, 255) via RQ_M * 2^-RQ_SH
  output  argmax of the int32 accumulators (lowest index on ties)
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
R2 = os.path.dirname(HERE)
V4 = os.path.dirname(R2)
REPO = os.path.dirname(os.path.dirname(V4))
sys.path.insert(0, os.path.join(V4, "tools"))
import gen_mem  # noqa: E402

BA = os.path.join(R2, "build_ann")
N_CAL = 2000


def calib_inputs():
    import torch
    import torchvision
    tf = torchvision.transforms.Compose([torchvision.transforms.ToTensor(), torchvision.transforms.Resize((8, 8))])
    ds = torchvision.datasets.MNIST(os.path.join(REPO, "Train", "datasets", "mnist"), train=True, download=False,
                                    transform=tf)
    return np.stack([ds[k][0].view(-1).numpy() for k in range(N_CAL)]).astype(np.float64)


def test_inputs_u8():
    X = np.load(os.path.join(R2, "results", "analog_inputs.npy"))  # written by stats.py
    return np.clip(np.round(X * 255), 0, 255).astype(np.int64)


def rq_params(r):
    """RQ_M (<2^16) and RQ_SH with RQ_M * 2^-RQ_SH ~= r."""
    sh = 0
    while round(r * 2 ** (sh + 1)) < (1 << 16) and sh < 40:
        sh += 1
    return int(round(r * 2 ** sh)), sh


def quantise(topo):
    Ws = gen_mem.load_weights(topo)
    qs, _, alphas, _ = gen_mem.quantise(Ws, 28.0, "layer", 8)  # same int8 bits as the SNN synMem
    Xc = calib_inputs()
    h = Xc
    s_in = 1.0 / 255.0
    M, SH, scales = [], [], [s_in]
    for l, W in enumerate(Ws):
        h = h @ W.T
        if l < len(Ws) - 1:
            h = np.maximum(h, 0)
            s_out = float(h.max()) / 255.0
            m, sh = rq_params(s_in * alphas[l] / s_out)
            M.append(m)
            SH.append(sh)
            scales.append(s_out)
            s_in = s_out
        else:
            M.append(1)
            SH.append(1)
    return Ws, qs, M, SH, scales, alphas


def forward_int(qs, M, SH, A):
    """bit-exact model of ann_q8.sv; A: (n, N_IN) uint8 -> (scores, pred)."""
    a = A.astype(np.int64)
    for l, q in enumerate(qs):
        acc = a @ q.T.astype(np.int64)
        assert np.abs(acc).max() < 2 ** 31
        if l < len(qs) - 1:
            r = (acc * M[l] + (1 << (SH[l] - 1))) >> SH[l]
            a = np.clip(r, 0, 255)
        else:
            return acc, acc.argmax(1)


def tab(name, vals, w=32):
    return "localparam logic [N_LAYERS-1:0][%d:0] %s = {%s};" % (
        w - 1, name, ", ".join("%d'd%d" % (w, v) for v in reversed(vals)))


def build(topo):
    Ws, qs, M, SH, scales, alphas = quantise(topo)
    d = os.path.join(BA, "ann_" + topo)
    os.makedirs(d, exist_ok=True)
    sizes = [q.shape[0] for q in qs]
    fanins = [q.shape[1] for q in qs]
    fanin = max(fanins)
    starts = list(np.cumsum([0] + sizes[:-1]))
    with open(os.path.join(d, "syn.mem"), "w") as f:
        f.write("// synMem: int8 weights, addr = neuron*%d + slot (same bits as the SNN builds)\n" % fanin)
        for q in qs:
            for row in q:
                f.write(" ".join(gen_mem.hex_w(v, 8) for v in list(row) + [0] * (fanin - len(row))) + "\n")
    abuf = max([fanins[0]] + sizes[:-1])
    p = ["// generated by revision2/tools/gen_ann.py -- do not edit", "// topology=%s" % topo,
         "localparam int N_IN     = %d;" % fanins[0],
         "localparam int N_NEU    = %d;" % sum(sizes),
         "localparam int N_LAYERS = %d;" % len(qs),
         "localparam int FANIN    = %d;" % fanin,
         "localparam int N_OUT    = %d;" % sizes[-1],
         "localparam int ABUF     = %d;" % abuf,
         tab("L_START", starts), tab("L_SIZE", sizes), tab("L_FANIN", fanins), tab("RQ_M", M), tab("RQ_SH", SH)]
    open(os.path.join(d, "ann_params.svh"), "w").write("\n".join(p) + "\n")
    json.dump(dict(topology=topo, sizes=sizes, fanins=fanins, starts=[int(s) for s in starts], RQ_M=M, RQ_SH=SH,
                   act_scales=scales, w_scales=alphas, calib="max ReLU activation, %d MNIST train images" % N_CAL),
              open(os.path.join(d, "quant.json"), "w"), indent=1)
    np.savez(os.path.join(d, "weights_float.npz"), *Ws)
    print("wrote", d, "sizes", sizes, "RQ_M", M, "RQ_SH", SH)


def cycles(topo):
    q = json.load(open(os.path.join(BA, "ann_" + topo, "quant.json")))
    n_in = q["fanins"][0]
    run = 2 + sum(s * (f + 3) for s, f in zip(q["sizes"][:-1], q["fanins"][:-1])) + q["sizes"][-1] * (q["fanins"][-1] + 2)
    return 2 + 2 * n_in + run  # CLEAR + N_IN LOADs + RUN


def model(topo):
    d = os.path.join(BA, "ann_" + topo)
    q = json.load(open(os.path.join(d, "quant.json")))
    rows = [l.split() for l in open(os.path.join(d, "syn.mem")) if not l.startswith("//")]
    W = np.array([[int(x, 16) for x in r] for r in rows])
    W = np.where(W >= 128, W - 256, W)
    qs = [W[s:s + n, :f] for s, n, f in zip(q["starts"], q["sizes"], q["fanins"])]
    A = test_inputs_u8()
    lab = np.load(os.path.join(V4, "data", "spikes.npz"))["labels"]
    sc, pr = forward_int(qs, q["RQ_M"], q["RQ_SH"], A)
    with open(os.path.join(d, "ref_int.txt"), "w") as f:
        for k in range(len(lab)):
            f.write("IMG %d LABEL %d PRED %d SCORES %s\n" % (k, lab[k], pr[k], " ".join(map(str, sc[k]))))
    z = np.load(os.path.join(d, "weights_float.npz"))
    Ws = [z["arr_%d" % i] for i in range(len(z.files))]
    h = np.load(os.path.join(R2, "results", "analog_inputs.npy"))
    for i, Wl in enumerate(Ws):
        h = h @ Wl.T
        if i < len(Ws) - 1:
            h = np.maximum(h, 0)
    fl = h.argmax(1) == lab
    it = pr == lab
    print("ann_%s: int8 acc %.1f%%  float acc %.1f%%  agreement %.1f%%  cycles/img %d (%.3f ms @50MHz)" % (
        topo, 100 * it.mean(), 100 * fl.mean(), 100 * (pr == h.argmax(1)).mean(), cycles(topo), cycles(topo) / 50e3))


def data():
    os.makedirs(BA, exist_ok=True)
    A = test_inputs_u8()
    lab = np.load(os.path.join(V4, "data", "spikes.npz"))["labels"]
    with open(os.path.join(BA, "inputs.mem"), "w") as f:
        for row in A:
            f.write(" ".join("%02x" % v for v in row) + "\n")
    open(os.path.join(BA, "labels.mem"), "w").write("\n".join("%x" % l for l in lab) + "\n")
    print("wrote", BA, A.shape)


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "build":
        build(sys.argv[2])
    elif cmd == "model":
        model(sys.argv[2])
    elif cmd == "data":
        data()
